/* ============================================================
   generate-manifest.js
   ------------------------------------------------------------
   Scans the  images/  folder and rewrites  images.js  with the
   list of photos it finds. Run it after adding/removing photos:

       node generate-manifest.js

   No dependencies needed — plain Node.js.
   ============================================================ */

const fs = require("fs");
const path = require("path");

const IMAGES_DIR = path.join(__dirname, "images");
const OUTPUT = path.join(__dirname, "images.js");
const EXT = new Set([
  // photos
  ".jpg", ".jpeg", ".png", ".webp", ".gif", ".avif",
  // videos
  ".mp4", ".webm", ".mov", ".m4v", ".ogv",
]);

if (!fs.existsSync(IMAGES_DIR)) {
  fs.mkdirSync(IMAGES_DIR);
  console.log("Created empty images/ folder. Add your photos and run again.");
}

const files = fs
  .readdirSync(IMAGES_DIR)
  .filter((f) => EXT.has(path.extname(f).toLowerCase()))
  // Natural-ish sort so photo2 comes before photo10.
  .sort((a, b) =>
    a.localeCompare(b, undefined, { numeric: true, sensitivity: "base" })
  );

const list = files.map((f) => '  "images/' + f.replace(/"/g, '\\"') + '"').join(",\n");

const content =
  "/* AUTO-GENERATED by generate-manifest.js — do not edit by hand. */\n" +
  "window.GALLERY_IMAGES = [\n" +
  (list ? list + "\n" : "") +
  "];\n";

fs.writeFileSync(OUTPUT, content, "utf8");
console.log("Wrote " + files.length + " photo(s) to images.js");
files.forEach((f) => console.log("   - " + f));
